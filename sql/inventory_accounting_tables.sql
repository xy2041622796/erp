CREATE TABLE IF NOT EXISTS `erp_inventory_cost_calc` (
  `id` varchar(64) DEFAULT NULL COMMENT '记录ID',
  `period_code` varchar(7) DEFAULT NULL COMMENT '期间编码，格式YYYY-MM',
